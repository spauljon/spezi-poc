#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# bootstrap.sh -- starts the POC stack (compose project spezi-poc).
# Adapted from the governance project's bin/bootstrap.sh.
#
# One path, first run or not (the database initializes itself; see db/startup/10-poc-init.sh):
#   1. Ensures credentials and TLS material exist (db/make-env.sh etc., never overwrites)
#   2. Starts oracle and waits until it is healthy. Healthy means the database is up AND db/init.sh succeeded
#      (PDBs, users, HAPI and analytics schemas); on a first run that takes several minutes. A failed init is reported at once.
#   3. Loads Keycloak's schema into KEYCLOAKPDB (idp/db-migrate.sh): Keycloak must not start before it exists
#   4. Starts the rest of the stack (HAPI, Keycloak and proxy, analytics worker and API, web) and WAITS until every
#      service reports healthy, then ensures the synthetic patient exists
# Step 3 is idempotent, so rerunning is always safe. To start from nothing: scripts/reset.sh.
# ---------------------------------------------------------------------------
set -euo pipefail

RUN_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE_CMD="${RUN_DIR}/scripts/compose.sh"
ORACLE_CONTAINER=spezi-poc-oracle

log()  { echo "✅ $*"; }
fail() { echo "❌ ERROR: $*" >&2; exit 1; }

assert_docker_running() {
  if ! docker info > /dev/null 2>&1; then
    if [[ "$OSTYPE" == "darwin"* ]]; then
      echo "Starting Docker Desktop..."
      open -a Docker
      until docker info > /dev/null 2>&1; do sleep 2; done
      echo "Docker Desktop ready."
    else
      fail "Docker daemon is not running"
    fi
  fi
}

# Waits for oracle to be healthy, which includes its init. Gives up at once if the init failed or the container
# died, with the log, rather than waiting out the healthcheck's start period.
wait_for_oracle() {
  local i state status tries=360   # 30 minutes: a first run creates the database and three PDBs
  for i in $(seq 1 "${tries}"); do
    state=$(docker inspect -f '{{.State.Status}}' "${ORACLE_CONTAINER}" 2>/dev/null || echo missing)
    [ "${state}" = "running" ] || { docker logs --tail 40 "${ORACLE_CONTAINER}" >&2 || true; fail "oracle is ${state}."; }
    status=$(docker inspect -f '{{.State.Health.Status}}' "${ORACLE_CONTAINER}" 2>/dev/null || echo unknown)
    [ "${status}" = "healthy" ] && return 0
    if [ "$(docker exec "${ORACLE_CONTAINER}" bash /opt/poc/db/init-status.sh 2>/dev/null || true)" = "failed" ]; then
      docker logs --tail 60 "${ORACLE_CONTAINER}" >&2 || true
      fail "the database init (db/init.sh) failed; see the log above. It is idempotent: fix the cause and rerun."
    fi
    [ $((i % 6)) -ne 0 ] || echo "   ... waiting for oracle (database creation and init; first run takes several minutes)"
    sleep 5
  done
  fail "oracle did not become healthy within 30 minutes."
}

# Keycloak's schema is generated by Keycloak itself and loaded as the schema owner. It must exist before Keycloak
# starts, so this runs between oracle and the rest of the stack. The Keycloak image is built here (it carries the
# Oracle JDBC driver; the first build downloads two jars, verified against pinned SHA-256 checksums).
migrate_keycloak_schema() {
  log "Keycloak image and schema ..."
  ${COMPOSE_CMD} build keycloak
  "${RUN_DIR}/idp/db-migrate.sh"
}

# Starts everything and returns only when every service is healthy (or fails loudly with what is not).
start_all() {
  ${COMPOSE_CMD} up -d --build --wait --wait-timeout 900 || {
    ${COMPOSE_CMD} ps >&2 || true
    fail "a service did not become healthy; see 'make stack-ps' and 'docker logs <container>'."
  }
}

# The capture app creates the patient on its first sync; the web app needs one to show, so make sure it exists
# (idempotent conditional create). Best effort: the stack is up either way, and the message says how to retry.
ensure_patient() {
  if command -v python3 > /dev/null 2>&1 && python3 "${RUN_DIR}/hapi/auth.py" seed > /dev/null 2>&1; then
    log "Synthetic patient is present."
  else
    echo "note: could not confirm the synthetic patient; run 'python3 hapi/auth.py seed' (needs python3 and curl)" >&2
  fi
}

start_oracle() {
  log "Starting oracle (the database initializes itself; the first run takes several minutes) ..."
  ${COMPOSE_CMD} up -d --build oracle
  wait_for_oracle
  log "oracle is healthy: database initialized."
}

assert_docker_running

# create gitignored credentials where absent (never overwrites)
"${RUN_DIR}/db/make-env.sh"
"${RUN_DIR}/idp/make-env.sh"
"${RUN_DIR}/analytics/make-env.sh"   # derived: only the keys the analytics containers need

# create the local CA and the HAPI, proxy and Keycloak certificates where absent (idempotent; keys live outside the repo)
"${RUN_DIR}/scripts/make-tls.sh"

start_oracle
migrate_keycloak_schema
start_all

ensure_patient

log "spezi-poc is up. Verify with: make stack-verify"
